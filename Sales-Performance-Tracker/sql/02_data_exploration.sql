USE sales_performance_tracker;
SELECT COUNT(*) AS order_lines, COUNT(DISTINCT ORDERNUMBER) AS orders,
 COUNT(DISTINCT CUSTOMERNAME) AS customers, COUNT(DISTINCT PRODUCTCODE) AS products,
 MIN(ORDERDATE) AS first_order, MAX(ORDERDATE) AS last_order FROM sales;
SELECT STATUS, COUNT(*) AS order_lines, COUNT(DISTINCT ORDERNUMBER) AS orders,
 ROUND(SUM(SALES),2) AS sales FROM sales GROUP BY STATUS ORDER BY sales DESC;
