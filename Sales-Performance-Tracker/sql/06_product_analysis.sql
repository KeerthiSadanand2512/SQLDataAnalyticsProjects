USE sales_performance_tracker;
SELECT PRODUCTLINE, ROUND(SUM(SALES),2) AS sales,
 ROUND(100.0*SUM(SALES)/(SELECT SUM(SALES) FROM sales),2) AS sales_share_pct,
 SUM(QUANTITYORDERED) AS units, COUNT(DISTINCT ORDERNUMBER) AS orders
FROM sales GROUP BY PRODUCTLINE ORDER BY sales DESC, PRODUCTLINE;
SELECT PRODUCTCODE, PRODUCTLINE, ROUND(SUM(SALES),2) AS sales, SUM(QUANTITYORDERED) AS units
FROM sales GROUP BY PRODUCTCODE, PRODUCTLINE ORDER BY sales DESC, PRODUCTCODE LIMIT 10;
