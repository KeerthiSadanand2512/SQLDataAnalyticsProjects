USE sales_performance_tracker;
CREATE TEMPORARY TABLE raw_sales (
ORDERNUMBER TEXT,
QUANTITYORDERED TEXT,
PRICEEACH TEXT,
ORDERLINENUMBER TEXT,
SALES TEXT,
ORDERDATE TEXT,
STATUS TEXT,
QTR_ID TEXT,
MONTH_ID TEXT,
YEAR_ID TEXT,
PRODUCTLINE TEXT,
MSRP TEXT,
PRODUCTCODE TEXT,
CUSTOMERNAME TEXT,
PHONE TEXT,
ADDRESSLINE1 TEXT,
ADDRESSLINE2 TEXT,
CITY TEXT,
STATE TEXT,
POSTALCODE TEXT,
COUNTRY TEXT,
TERRITORY TEXT,
CONTACTLASTNAME TEXT,
CONTACTFIRSTNAME TEXT,
DEALSIZE TEXT
);
LOAD DATA LOCAL INFILE '/absolute/path/Sales-Performance-Tracker/data/sales_data.csv'
INTO TABLE raw_sales CHARACTER SET utf8mb4
FIELDS TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"' ESCAPED BY '"'
LINES TERMINATED BY '\r\n' IGNORE 1 LINES
(ORDERNUMBER,QUANTITYORDERED,PRICEEACH,ORDERLINENUMBER,SALES,ORDERDATE,STATUS,QTR_ID,MONTH_ID,YEAR_ID,PRODUCTLINE,MSRP,PRODUCTCODE,CUSTOMERNAME,PHONE,ADDRESSLINE1,ADDRESSLINE2,CITY,STATE,POSTALCODE,COUNTRY,TERRITORY,CONTACTLASTNAME,CONTACTFIRSTNAME,DEALSIZE);
SHOW WARNINGS;
-- Stop if warnings appear or the count is not 2823.
SELECT COUNT(*) AS raw_lines FROM raw_sales;
START TRANSACTION;
DELETE FROM sales;
INSERT INTO sales (ORDERNUMBER,QUANTITYORDERED,PRICEEACH,ORDERLINENUMBER,SALES,ORDERDATE,STATUS,QTR_ID,MONTH_ID,YEAR_ID,PRODUCTLINE,MSRP,PRODUCTCODE,CUSTOMERNAME,PHONE,ADDRESSLINE1,ADDRESSLINE2,CITY,STATE,POSTALCODE,COUNTRY,TERRITORY,CONTACTLASTNAME,CONTACTFIRSTNAME,DEALSIZE)
SELECT NULLIF(ORDERNUMBER,''),NULLIF(QUANTITYORDERED,''),NULLIF(PRICEEACH,''),NULLIF(ORDERLINENUMBER,''),NULLIF(SALES,''),STR_TO_DATE(ORDERDATE,'%c/%e/%Y %H:%i'),NULLIF(STATUS,''),NULLIF(QTR_ID,''),NULLIF(MONTH_ID,''),NULLIF(YEAR_ID,''),NULLIF(PRODUCTLINE,''),NULLIF(MSRP,''),NULLIF(PRODUCTCODE,''),NULLIF(CUSTOMERNAME,''),NULLIF(PHONE,''),NULLIF(ADDRESSLINE1,''),NULLIF(ADDRESSLINE2,''),NULLIF(CITY,''),NULLIF(STATE,''),NULLIF(POSTALCODE,''),NULLIF(COUNTRY,''),NULLIF(TERRITORY,''),NULLIF(CONTACTLASTNAME,''),NULLIF(CONTACTFIRSTNAME,''),NULLIF(DEALSIZE,'') FROM raw_sales;
COMMIT;
DROP TEMPORARY TABLE raw_sales;
