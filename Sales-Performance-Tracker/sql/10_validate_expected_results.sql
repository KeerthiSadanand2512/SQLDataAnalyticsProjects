-- Run after scripts 01–09. Raises SQLSTATE 45000 on a regression.
USE sales_performance_tracker;
DROP PROCEDURE IF EXISTS validate_sales_tracker;
DELIMITER //
CREATE PROCEDURE validate_sales_tracker()
BEGIN
 IF (SELECT COUNT(*) FROM sales) <> 2823
 OR (SELECT COUNT(DISTINCT ORDERNUMBER) FROM sales) <> 307
 OR (SELECT COUNT(DISTINCT CUSTOMERNAME) FROM sales) <> 92
 OR (SELECT COUNT(DISTINCT PRODUCTCODE) FROM sales) <> 109
 OR (SELECT SUM(QUANTITYORDERED) FROM sales) <> 99067
 OR (SELECT SUM(SALES) FROM sales) <> 10032628.85
 OR (SELECT SUM(SALES) FROM sales WHERE STATUS='Shipped') <> 9291501.08
 OR (SELECT COUNT(*) FROM sales WHERE ABS(SALES-QUANTITYORDERED*PRICEEACH)>0.01) <> 1304
 OR (SELECT COUNT(*) FROM sales WHERE YEAR(ORDERDATE)<>YEAR_ID OR MONTH(ORDERDATE)<>MONTH_ID OR QUARTER(ORDERDATE)<>QTR_ID) <> 0
 OR (SELECT COUNT(*) FROM sales WHERE STATE IS NULL) <> 1486
 OR (SELECT COUNT(*) FROM sales WHERE POSTALCODE IS NULL) <> 76
 OR (SELECT COUNT(*) FROM sales WHERE ADDRESSLINE2 IS NULL) <> 2521
 OR (SELECT SUM(SALES) FROM sales WHERE PRODUCTLINE='Classic Cars') <> 3919615.66
 OR (SELECT SUM(SALES) FROM sales WHERE COUNTRY='USA') <> 3627982.83
 OR (SELECT SUM(SALES) FROM sales WHERE YEAR_ID=2005 AND MONTH_ID<=5) <> 1791486.71
 OR (SELECT COUNT(*) FROM customer_rfm) <> 92
 OR (SELECT COUNT(*) FROM customer_rfm WHERE segment='Champions') <> 17
 OR (SELECT SUM(monetary) FROM customer_rfm) <> 10032628.85
 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='FAIL: dataset or transformation differs from validated snapshot';
 END IF;
 SELECT 'PASS: expected snapshot assertions' AS validation;
END//
DELIMITER ;
CALL validate_sales_tracker();
DROP PROCEDURE validate_sales_tracker;
