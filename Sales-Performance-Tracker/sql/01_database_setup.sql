-- MySQL 8.0+; creates only the project schema. No databases are dropped.
CREATE DATABASE IF NOT EXISTS sales_performance_tracker CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE sales_performance_tracker;
CREATE TABLE IF NOT EXISTS sales (
  ORDERNUMBER INT NOT NULL,
  QUANTITYORDERED INT NOT NULL,
  PRICEEACH DECIMAL(14,2) NOT NULL,
  ORDERLINENUMBER INT NOT NULL,
  SALES DECIMAL(14,2) NOT NULL,
  ORDERDATE DATETIME NOT NULL,
  STATUS VARCHAR(255) NOT NULL,
  QTR_ID INT NOT NULL,
  MONTH_ID INT NOT NULL,
  YEAR_ID INT NOT NULL,
  PRODUCTLINE VARCHAR(255) NOT NULL,
  MSRP INT NOT NULL,
  PRODUCTCODE VARCHAR(255) NOT NULL,
  CUSTOMERNAME VARCHAR(255) NOT NULL,
  PHONE VARCHAR(255) NOT NULL,
  ADDRESSLINE1 VARCHAR(255) NOT NULL,
  ADDRESSLINE2 VARCHAR(255),
  CITY VARCHAR(255) NOT NULL,
  STATE VARCHAR(255),
  POSTALCODE VARCHAR(255),
  COUNTRY VARCHAR(255) NOT NULL,
  TERRITORY VARCHAR(255) NOT NULL,
  CONTACTLASTNAME VARCHAR(255) NOT NULL,
  CONTACTFIRSTNAME VARCHAR(255) NOT NULL,
  DEALSIZE VARCHAR(255) NOT NULL,
  PRIMARY KEY (ORDERNUMBER, ORDERLINENUMBER),
  INDEX idx_orderdate (ORDERDATE),
  INDEX idx_customer (CUSTOMERNAME),
  CHECK (QUANTITYORDERED > 0),
  CHECK (SALES >= 0)
);
