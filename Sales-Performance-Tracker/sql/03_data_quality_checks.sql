USE sales_performance_tracker;
-- Duplicate key query must return no rows.
SELECT ORDERNUMBER, ORDERLINENUMBER, COUNT(*) AS occurrences FROM sales
GROUP BY ORDERNUMBER,ORDERLINENUMBER HAVING COUNT(*) > 1;
SELECT SUM(CASE WHEN SALES < 0 OR QUANTITYORDERED <= 0 OR PRICEEACH < 0 THEN 1 ELSE 0 END) AS invalid_numeric_lines,
 SUM(CASE WHEN YEAR(ORDERDATE) <> YEAR_ID OR MONTH(ORDERDATE) <> MONTH_ID OR QUARTER(ORDERDATE) <> QTR_ID THEN 1 ELSE 0 END) AS calendar_mismatches,
 SUM(CASE WHEN ABS(SALES - QUANTITYORDERED*PRICEEACH) > 0.01 THEN 1 ELSE 0 END) AS sales_price_mismatches,
 SUM(CASE WHEN ADDRESSLINE2 IS NULL THEN 1 ELSE 0 END) AS missing_addressline2,
 SUM(CASE WHEN STATE IS NULL THEN 1 ELSE 0 END) AS missing_state,
 SUM(CASE WHEN POSTALCODE IS NULL THEN 1 ELSE 0 END) AS missing_postalcode FROM sales;
-- Order attributes should be consistent across all its lines.
SELECT ORDERNUMBER FROM sales GROUP BY ORDERNUMBER
HAVING COUNT(DISTINCT CUSTOMERNAME)>1 OR COUNT(DISTINCT ORDERDATE)>1 OR COUNT(DISTINCT STATUS)>1;
-- SALES is authoritative: PRICEEACH is capped at 100 on many rows.
SELECT PRICEEACH, COUNT(*) AS line FROM sales WHERE PRICEEACH=100 GROUP BY PRICEEACH;
