USE sales_performance_tracker;
SELECT CUSTOMERNAME, COUNT(DISTINCT ORDERNUMBER) AS orders, ROUND(SUM(SALES),2) AS sales,
 ROUND(SUM(SALES)/COUNT(DISTINCT ORDERNUMBER),2) AS average_order_value,
 MIN(ORDERDATE) AS first_order, MAX(ORDERDATE) AS latest_order
FROM sales GROUP BY CUSTOMERNAME ORDER BY sales DESC,CUSTOMERNAME LIMIT 10;
WITH customers AS (SELECT CUSTOMERNAME, COUNT(DISTINCT ORDERNUMBER) AS orders FROM sales GROUP BY CUSTOMERNAME)
SELECT COUNT(*) AS customers, SUM(CASE WHEN orders>1 THEN 1 ELSE 0 END) AS repeat_customers,
 ROUND(100.0*SUM(CASE WHEN orders>1 THEN 1 ELSE 0 END)/COUNT(*),2) AS repeat_customer_pct FROM customers;
